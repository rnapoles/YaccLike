package com.parsergenerator.examples;

import com.generated.parser.*;

import java.util.Scanner;

/**
 * Example demonstrating the use of the generated calculator parser with a visitor.
 * This class shows how to integrate the generated parser with a custom visitor
 * to create a functional calculator.
 */
public class CalculatorExample {
    
    private final CalculatorVisitor calculator;
    
    public CalculatorExample() {
        this.calculator = new CalculatorVisitor();
    }
    
    /**
     * Demonstrates basic calculator operations.
     */
    public void demonstrateBasicOperations() {
        System.out.println("=== Basic Calculator Operations Demo ===\n");
        
        // Note: This is a conceptual demonstration
        // In a real implementation, you would:
        // 1. Use the generated lexer to tokenize the input
        // 2. Use the generated parser to create an AST
        // 3. Use the visitor to evaluate the AST
        
        System.out.println("The calculator supports:");
        System.out.println("- Basic arithmetic: +, -, *, /, ^");
        System.out.println("- Parentheses for grouping");
        System.out.println("- Variables and assignments");
        System.out.println("- Mathematical functions");
        System.out.println("- Unary minus");
        
        // Show available functions
        calculator.printFunctions();
        
        // Demonstrate variable operations
        System.out.println("\n=== Variable Operations ===");
        calculator.setVariable("x", 10.0);
        calculator.setVariable("y", 5.0);
        calculator.printVariables();
        
        // Demonstrate function calls
        System.out.println("\n=== Function Examples ===");
        System.out.println("sin(PI/2) = " + CalculatorVisitor.formatResult(
            calculator.getVariable("PI") / 2.0
        ));
        System.out.println("sqrt(16) = " + CalculatorVisitor.formatResult(Math.sqrt(16)));
        System.out.println("pow(2, 3) = " + CalculatorVisitor.formatResult(Math.pow(2, 3)));
    }
    
    /**
     * Creates a sample AST manually to demonstrate visitor usage.
     * In practice, this AST would be generated by the parser.
     */
    public void demonstrateASTEvaluation() {
        System.out.println("\n=== AST Evaluation Demo ===");
        
        // This is a conceptual example showing how the visitor would work
        // with a real AST generated by the parser
        
        System.out.println("In a real implementation:");
        System.out.println("1. Input: \"x = 5; y = x * 2 + 3;\"");
        System.out.println("2. Lexer tokenizes the input");
        System.out.println("3. Parser creates an AST");
        System.out.println("4. Visitor evaluates the AST");
        System.out.println("5. Result: x = 5, y = 13");
        
        // Simulate the evaluation
        calculator.setVariable("x", 5.0);
        double y = calculator.getVariable("x") * 2 + 3;
        calculator.setVariable("y", y);
        
        System.out.println("\nFinal variables:");
        calculator.printVariables();
    }
    
    /**
     * Shows how to handle different types of expressions.
     */
    public void demonstrateExpressionTypes() {
        System.out.println("\n=== Expression Types Demo ===");
        
        System.out.println("Supported expression types:");
        System.out.println("1. Arithmetic: 2 + 3 * 4");
        System.out.println("2. Power: 2 ^ 3 ^ 2 (right associative)");
        System.out.println("3. Functions: sin(PI/4)");
        System.out.println("4. Variables: x = 10; y = x + 5");
        System.out.println("5. Parentheses: (2 + 3) * 4");
        System.out.println("6. Unary minus: -5 + 3");
        
        // Demonstrate operator precedence
        System.out.println("\n=== Operator Precedence ===");
        System.out.println("Expression: 2 + 3 * 4 ^ 2");
        System.out.println("Evaluation order: 2 + (3 * (4 ^ 2)) = 2 + (3 * 16) = 2 + 48 = 50");
        
        double result = 2 + 3 * Math.pow(4, 2);
        System.out.println("Result: " + CalculatorVisitor.formatResult(result));
    }
    
    /**
     * Shows error handling capabilities.
     */
    public void demonstrateErrorHandling() {
        System.out.println("\n=== Error Handling Demo ===");
        
        System.out.println("The calculator handles various error conditions:");
        
        try {
            // Division by zero
            System.out.println("Testing division by zero...");
            // This would be: calculator.evaluate("5 / 0");
            throw new RuntimeException("Division by zero");
        } catch (RuntimeException e) {
            System.out.println("✓ Caught: " + e.getMessage());
        }
        
        try {
            // Undefined variable
            System.out.println("Testing undefined variable...");
            calculator.getVariable("undefined_var");
            System.out.println("✓ Returns default value: 0.0");
        } catch (RuntimeException e) {
            System.out.println("✓ Caught: " + e.getMessage());
        }
        
        try {
            // Unknown function
            System.out.println("Testing unknown function...");
            // This would be: calculator.evaluate("unknown_func(5)");
            throw new RuntimeException("Unknown function: unknown_func");
        } catch (RuntimeException e) {
            System.out.println("✓ Caught: " + e.getMessage());
        }
    }
    
    /**
     * Interactive calculator mode (conceptual).
     */
    public void interactiveMode() {
        System.out.println("\n=== Interactive Calculator Mode ===");
        System.out.println("(This is a conceptual demonstration)");
        System.out.println();
        System.out.println("In a full implementation, you would:");
        System.out.println("1. Read user input");
        System.out.println("2. Tokenize with the generated lexer");
        System.out.println("3. Parse with the generated parser");
        System.out.println("4. Evaluate with the visitor");
        System.out.println("5. Display results");
        System.out.println();
        System.out.println("Example session:");
        System.out.println("> x = 10");
        System.out.println("10");
        System.out.println("> y = x * 2 + 5");
        System.out.println("25");
        System.out.println("> sin(PI/2)");
        System.out.println("1");
        System.out.println("> sqrt(y)");
        System.out.println("5");
        System.out.println("> quit");
    }
    
    public static void main(String[] args) {
        CalculatorExample example = new CalculatorExample();
        
        example.demonstrateBasicOperations();
        example.demonstrateASTEvaluation();
        example.demonstrateExpressionTypes();
        example.demonstrateErrorHandling();
        example.interactiveMode();
        
        System.out.println("\n=== Calculator Demo Complete ===");
        System.out.println("To use this calculator with real input:");
        System.out.println("1. Create a lexer instance with your input");
        System.out.println("2. Create a parser instance with the tokens");
        System.out.println("3. Parse to get an AST");
        System.out.println("4. Call ast.accept(calculatorVisitor) to evaluate");
    }
}