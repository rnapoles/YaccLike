    /**
     * Writes generated files to the temporary directory.
     */
    private Map<String, Path> writeGeneratedFiles(GeneratedCode result) throws IOException {
        Map<String, Path> files = new HashMap<>();
        
        for (String fileName : result.getFileNames()) {
            Path filePath = tempDir.resolve(fileName);
            Files.write(filePath, result.getFileContent(fileName).getBytes());
            files.put(fileName, filePath);
        }
        
        return files;
    }
    
    /**
     * Compiles the generated Java code to verify it's syntactically correct.
     */
    private boolean compileGeneratedCode(Collection<Path> sourceFiles) {
        JavaCompiler compiler = ToolProvider.getSystemJavaCompiler();
        if (compiler == null) {
            // Skip compilation test if no compiler available (e.g., in JRE-only environment)
            return true;
        }
        
        StandardJavaFileManager fileManager = compiler.getStandardFileManager(null, null, null);
        
        try {
            // Convert paths to File objects
            List<File> files = new ArrayList<>();
            for (Path path : sourceFiles) {
                files.add(path.toFile());
            }
            
            Iterable<? extends JavaFileObject> compilationUnits = 
                fileManager.getJavaFileObjectsFromFiles(files);
            
            // Set up compilation options
            List<String> options = Arrays.asList(
                "-cp", System.getProperty("java.class.path"),
                "-d", tempDir.toString()
            );
            
            JavaCompiler.CompilationTask task = compiler.getTask(
                null, fileManager, null, options, null, compilationUnits);
            
            return task.call();
        } catch (Exception e) {
            e.printStackTrace();
            return false;
        } finally {
            try {
                fileManager.close();
            } catch (IOException e) {
                // Ignore
            }
        }
    }
